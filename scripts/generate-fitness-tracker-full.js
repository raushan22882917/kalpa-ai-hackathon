// Create directories
function createDirectories(baseDir, structure) {
  Object.keys(structure).forEach(section => {
    const sectionDir = path.join(baseDir, section);
    Object.keys(structure[section]).forEach(dir => {
      const fullPath = path.join(sectionDir, dir);
      if (!fs.existsSync(fullPath)) {
        fs.mkdirSync(fullPath, { recursive: true });
        console.log(`✅ Created: ${fullPath}`);
      }
    });
  });
}

